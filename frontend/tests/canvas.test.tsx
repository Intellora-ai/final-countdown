  const diagram = { title: 'Energy transfer', explanation: 'Energy moves.', blocks: [{ kind: 'diagram', title: 'Flow', nodes: [{ id: 'a', label: 'Source' }, { id: 'b', label: 'Store' }], edges: [{ from: 'a', to: 'b', label: 'moves' }] }] }
