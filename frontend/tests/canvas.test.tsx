it('moves the saved-history selection marker to the answer the learner opens', () => {
  const entries = ['First saved idea', 'Second saved idea'].map((title, index) => ({ id: String(index), question: title, lesson: { title, explanation: title, blocks: [] } }))
  localStorage.setItem('visual-canvas/v1', JSON.stringify(entries))
  vi.stubGlobal('fetch', vi.fn<typeof fetch>().mockResolvedValue(Response.json({ modelConfigured: true })))
  render(<Canvas />)
  fireEvent.click(screen.getByRole('button', { name: 'Saved lessons' }))
  const first = screen.getByRole('button', { name: entries[0].lesson.title })
  const second = screen.getByRole('button', { name: entries[1].lesson.title })
  expect(first.classList.contains('active')).toBe(false)
  expect(second.classList.contains('active')).toBe(true)
  fireEvent.click(first)
  expect(screen.getByRole('heading', { level: 1 }).textContent).toBe(entries[0].lesson.title)
  expect(first.classList.contains('active')).toBe(true)
  expect(second.classList.contains('active')).toBe(false)
})
