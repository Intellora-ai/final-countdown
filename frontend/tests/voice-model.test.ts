import { beforeEach, expect, it, vi } from 'vitest'
const boundary = vi.hoisted(() => ({ load: vi.fn(), tokenizer: vi.fn(), generate: vi.fn(), env: {} }))
vi.mock('@huggingface/transformers', () => ({ StyleTextToSpeech2Model: { from_pretrained: boundary.load }, AutoTokenizer: { from_pretrained: boundary.tokenizer }, env: boundary.env }))
vi.mock('kokoro-js', () => ({ KokoroTTS: class { generate = boundary.generate } }))
beforeEach(() => {
  vi.resetModules(); vi.clearAllMocks()
  boundary.load.mockResolvedValue({}); boundary.tokenizer.mockResolvedValue({})
  boundary.generate.mockResolvedValue({ audio: new Float32Array([0, .2, -.2]), sampling_rate: 24000, toWav: () => new Uint8Array([82, 73, 70, 70]) })
})
it('uses immutable CPU weights and returns generated waveform bytes for arbitrary text', async () => {
  const { generateSpeech, VOICE_MODEL, VOICE_REVISION } = await import('../server/voice-model')
  expect(await generateSpeech('A new subject, Δ and 3.14.', new AbortController().signal)).toEqual(Buffer.from('RIFF'))
  expect(boundary.load).toHaveBeenCalledWith(VOICE_MODEL, expect.objectContaining({ revision: VOICE_REVISION, device: 'cpu', dtype: 'q8' }))
  expect(boundary.generate).toHaveBeenCalledWith('A new subject, Δ and 3.14.', { voice: 'af_heart' })
  await generateSpeech('Another topic.', new AbortController().signal)
  expect(boundary.load).toHaveBeenCalledOnce()
})
it.each([new Float32Array(), new Float32Array([NaN]), new Float32Array([Infinity]), new Float32Array(24000 * 60 + 1)])('rejects unusable generated waveforms without returning audio', async audio => {
  boundary.generate.mockResolvedValue({ audio, sampling_rate: 24000, toWav: () => new Uint8Array() })
  const { generateSpeech } = await import('../server/voice-model')
  await expect(generateSpeech('An idea.', new AbortController().signal)).rejects.toThrow('Invalid generated audio')
})
it('retries initialization after failure without permanently poisoning the model cache', async () => {
  boundary.load.mockRejectedValueOnce(new Error('download failed'))
  const { generateSpeech } = await import('../server/voice-model')
  await expect(generateSpeech('First.', new AbortController().signal)).rejects.toThrow('download failed')
  await expect(generateSpeech('Second.', new AbortController().signal)).resolves.toEqual(Buffer.from('RIFF'))
})
it('serializes native inference and skips an interrupted queued turn', async () => {
  let finish!: (value: unknown) => void
  boundary.generate.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
  const { generateSpeech } = await import('../server/voice-model')
  const first = generateSpeech('First.', new AbortController().signal)
  await vi.waitFor(() => expect(finish).toBeDefined())
  const controller = new AbortController()
  const second = generateSpeech('Cancelled.', controller.signal); void second.catch(() => {})
  controller.abort(); expect(boundary.generate).toHaveBeenCalledOnce()
  finish({ audio: new Float32Array([.2]), sampling_rate: 24000, toWav: () => new Uint8Array([82]) })
  await first; await expect(second).rejects.toThrow()
  await generateSpeech('Third.', new AbortController().signal)
  expect(boundary.generate.mock.calls.map(call => call[0])).toEqual(['First.', 'Third.'])
})
it('discards inference completed after interruption', async () => {
  const controller = new AbortController()
  boundary.generate.mockImplementation(async () => { controller.abort(); return { audio: new Float32Array([.1]), sampling_rate: 24000, toWav: () => new Uint8Array() } })
  const { generateSpeech } = await import('../server/voice-model')
  await expect(generateSpeech('Interrupted.', controller.signal)).rejects.toThrow()
})
it('does not start inference when cancelled during model loading', async () => {
  const controller = new AbortController()
  boundary.load.mockImplementation(async () => { controller.abort(); return {} })
  const { generateSpeech } = await import('../server/voice-model')
  await expect(generateSpeech('Interrupted.', controller.signal)).rejects.toThrow()
  expect(boundary.generate).not.toHaveBeenCalled()
})
